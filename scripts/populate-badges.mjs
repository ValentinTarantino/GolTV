#!/usr/bin/env node
// Populates src/lib/badges-populated.ts with SportsDB badge URLs for the
// given team names. Throttled (1s between requests) to avoid the free-tier
// rate limit. Run manually when you notice a missing crest:
//
//   node scripts/populate-badges.mjs "Team A" "Team B" ...
//   node scripts/populate-badges.mjs --file teams.txt
//
// Existing entries in badges-populated.ts are preserved; new ones are merged.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const SPORTSDB_KEY = "123";
const SPORTSDB_BASE = "https://www.thesportsdb.com/api/v1/json";
const OUT_FILE = path.join(__dirname, "..", "src", "lib", "badges-populated.ts");

function normalize(name) {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]/g, "")
    .trim();
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

async function searchBadge(query) {
  const url = `${SPORTSDB_BASE}/${SPORTSDB_KEY}/searchteams.php?t=${encodeURIComponent(query)}`;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url);
      if (res.status === 429 || res.status >= 500) {
        if (attempt < 2) {
          await sleep(1000 * (attempt + 1));
          continue;
        }
        return null;
      }
      if (!res.ok) return null;
      const data = await res.json();
      const teams = (data.teams || []).filter((t) => t.strSport === "Soccer");
      if (teams.length === 0) return null;
      const pick = teams.find((t) => t.strBadge) || teams[0];
      return pick.strBadge || null;
    } catch {
      if (attempt < 2) {
        await sleep(1000 * (attempt + 1));
        continue;
      }
      return null;
    }
  }
  return null;
}

function loadExisting() {
  if (!fs.existsSync(OUT_FILE)) return {};
  const src = fs.readFileSync(OUT_FILE, "utf8");
  const objMatch = src.match(/Record<string, string> = \{([\s\S]*?)\};/);
  if (!objMatch) return {};
  const entries = {};
  const re = /"([^"]+)":\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(objMatch[1])) !== null) {
    entries[m[1]] = m[2];
  }
  return entries;
}

function writeOut(entries) {
  const lines = Object.keys(entries)
    .sort()
    .map((k) => `  "${k}": "${entries[k]}",`);
  const content = `// Auto-generated by scripts/populate-badges.mjs — do not edit by hand.
// Maps normalized team names to SportsDB badge URLs.
// The populate script appends entries here so runtime never has to hit the
// SportsDB search API for these teams (avoids rate limiting).
export const POPULATED_BADGES: Record<string, string> = {
${lines.join("\n")}
};
`;
  fs.writeFileSync(OUT_FILE, content, "utf8");
}

async function main() {
  const args = process.argv.slice(2);
  let teams = [];

  if (args.includes("--file")) {
    const idx = args.indexOf("--file");
    const file = args[idx + 1];
    if (!file || !fs.existsSync(file)) {
      console.error("Usage: node scripts/populate-badges.mjs --file <teams.txt>");
      process.exit(1);
    }
    teams = fs
      .readFileSync(file, "utf8")
      .split(/\r?\n/)
      .map((l) => l.trim())
      .filter((l) => l && !l.startsWith("#"));
  } else {
    teams = args.filter((a) => !a.startsWith("--"));
  }

  if (teams.length === 0) {
    console.error('Usage: node scripts/populate-badges.mjs "Team A" "Team B" ...');
    console.error('   or: node scripts/populate-badges.mjs --file teams.txt');
    process.exit(1);
  }

  const existing = loadExisting();
  let added = 0;
  let skipped = 0;
  let failed = 0;

  for (const team of teams) {
    const key = normalize(team);
    if (!key) continue;
    if (existing[key]) {
      console.log(`SKIP (exists): ${team} -> ${existing[key]}`);
      skipped++;
      continue;
    }
    await sleep(1000);
    const badge = await searchBadge(team);
    if (badge) {
      existing[key] = badge;
      console.log(`ADD: ${team} -> ${badge}`);
      added++;
    } else {
      console.log(`FAIL: ${team} (not found or rate-limited)`);
      failed++;
    }
  }

  if (added > 0) {
    writeOut(existing);
    console.log(`\nWrote ${added} new entries to ${OUT_FILE}`);
  } else {
    console.log("\nNo new entries to write.");
  }
  console.log(`Done: ${added} added, ${skipped} skipped, ${failed} failed.`);
}

main().catch((e) => {
  console.error("ERR", e);
  process.exit(1);
});
